#!/usr/bin/env node
// Resync the git ward-files FROM the live handcrafted map, so git is an
// accurate, diffable, parseable source of truth again (the existing
// district-*.js modules had drifted to ~12% overlap with the live DB).
//
// It partitions the live tiles by poi.parentName (unparented tiles ->
// "_core") and writes one src/data/whitemarch-districts/district-<slug>.js
// per group, in the schema the seed script already consumes
// (DISTRICT_ID / DISTRICT_NAME / BOUNDING_BOX / TILES / STRUCTURES /
// SERVICES). Because each tile has exactly one parent, the partition is
// collision-free by construction and re-merging the files reproduces the
// live row byte-for-byte (verified by --check).
//
// USAGE
//   node scripts/whitemarch-export-districts.mjs --in <snapshot.json> --out <dir>
//   node scripts/whitemarch-export-districts.mjs --from-db --out <dir>
//   node scripts/whitemarch-export-districts.mjs --in <snapshot.json> --check   # round-trip only, no write

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";

const args = process.argv.slice(2);
const opt = (n, d = null) => { const i = args.indexOf(n); return i >= 0 && i + 1 < args.length ? args[i + 1] : d; };
const flag = (n) => args.includes(n);

async function loadRow() {
  const inFile = opt("--in");
  if (inFile) {
    const raw = JSON.parse(readFileSync(inFile, "utf8"));
    return { tiles: raw.tiles ?? raw, sealed_structures: raw.sealed_structures ?? [] };
  }
  if (flag("--from-db")) {
    const url = process.env.SUPABASE_URL, key = process.env.SUPABASE_SERVICE_KEY;
    if (!url || !key) throw new Error("--from-db needs SUPABASE_URL + SUPABASE_SERVICE_KEY");
    const res = await fetch(`${url}/rest/v1/handcrafted_map?id=eq.whitemarch&select=tiles,sealed_structures`,
      { headers: { apikey: key, Authorization: `Bearer ${key}` } });
    if (!res.ok) throw new Error(`DB read failed: ${res.status}`);
    return (await res.json())[0];
  }
  throw new Error("provide --in <file.json> or --from-db");
}

const slug = (s) => s.toLowerCase().replace(/&/g, "and").replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");

function groupTiles(tiles) {
  const groups = new Map();           // key -> { id, name, tiles: {k:v} }
  for (const [k, v] of Object.entries(tiles)) {
    const parent = v.poi?.parentName;
    const id = parent ? slug(parent) : "_core";
    const name = parent || "Whitemarch Core (walls, streets, civic)";
    if (!groups.has(id)) groups.set(id, { id, name, tiles: {} });
    groups.get(id).tiles[k] = v;
  }
  return groups;
}

// Assign each sealed_structure to the group that owns the parentName of its
// interior tiles (fallback: _core). Each structure is emitted exactly once.
function assignStructures(structures, tiles) {
  const out = new Map();
  for (const s of structures) {
    const counts = new Map();
    for (const cell of s.interior || []) {
      const v = tiles[`${cell.x},${cell.y}`];
      const id = v?.poi?.parentName ? slug(v.poi.parentName) : "_core";
      counts.set(id, (counts.get(id) || 0) + 1);
    }
    const owner = [...counts.entries()].sort((a, b) => b[1] - a[1])[0]?.[0] || "_core";
    if (!out.has(owner)) out.set(owner, []);
    out.get(owner).push(s);
  }
  return out;
}

function bbox(tileKeys) {
  let xmin = Infinity, xmax = -Infinity, ymin = Infinity, ymax = -Infinity;
  for (const k of tileKeys) {
    const [x, y] = k.split(",").map(Number);
    xmin = Math.min(xmin, x); xmax = Math.max(xmax, x);
    ymin = Math.min(ymin, y); ymax = Math.max(ymax, y);
  }
  return { xmin, xmax, ymin, ymax };
}

const sortKeys = (keys) => keys.sort((a, b) => {
  const [ax, ay] = a.split(",").map(Number), [bx, by] = b.split(",").map(Number);
  return ay - by || ax - bx;
});

function emitModule(g, structs) {
  const keys = sortKeys(Object.keys(g.tiles));
  const box = bbox(keys);
  const services = [...new Set(keys.map((k) => g.tiles[k].poi?.service).filter(Boolean))].sort();
  const L = [];
  L.push(`// AUTO-GENERATED by scripts/whitemarch-export-districts.mjs from the live`);
  L.push(`// handcrafted_map row. This file is a faithful snapshot of ward`);
  L.push(`// "${g.name}" — edit here and re-seed, or edit in the MapEditor and`);
  L.push(`// re-export. Do not hand-merge; regenerate.`);
  L.push(`export const DISTRICT_ID   = ${JSON.stringify(g.id)};`);
  L.push(`export const DISTRICT_NAME = ${JSON.stringify(g.name)};`);
  L.push(`export const BOUNDING_BOX  = ${JSON.stringify(box)};`);
  L.push(`export const TILES = {`);
  for (const k of keys) L.push(`  ${JSON.stringify(k)}: ${JSON.stringify(g.tiles[k])},`);
  L.push(`};`);
  L.push(`export const STRUCTURES = ${JSON.stringify(structs || [], null, 2)};`);
  L.push(`export const SERVICES = ${JSON.stringify(services, null, 2)};`);
  return L.join("\n") + "\n";
}

// Re-merge emitted groups and assert byte-equality with the source row.
function roundTripCheck(groups, structAssign, row) {
  const merged = {};
  for (const g of groups.values()) for (const [k, v] of Object.entries(g.tiles)) {
    if (k in merged) throw new Error(`round-trip: collision at ${k}`);
    merged[k] = v;
  }
  const a = JSON.stringify(row.tiles, Object.keys(row.tiles).sort());
  const b = JSON.stringify(merged, Object.keys(merged).sort());
  if (a !== b) throw new Error("round-trip: merged tiles differ from source");
  let nStruct = 0; for (const arr of structAssign.values()) nStruct += arr.length;
  if (nStruct !== (row.sealed_structures || []).length)
    throw new Error(`round-trip: structure count ${nStruct} != ${(row.sealed_structures || []).length}`);
  return Object.keys(merged).length;
}

async function main() {
  const row = await loadRow();
  const groups = groupTiles(row.tiles);
  const structAssign = assignStructures(row.sealed_structures || [], row.tiles);

  const n = roundTripCheck(groups, structAssign, row);
  console.error(`[export] round-trip OK: ${n} tiles re-merge identically; ${groups.size} groups`);

  if (flag("--check")) { console.error("[export] --check only, no files written."); return; }

  const outDir = opt("--out");
  if (!outDir) throw new Error("provide --out <dir> (or --check)");
  mkdirSync(outDir, { recursive: true });
  const manifest = [];
  for (const g of [...groups.values()].sort((a, b) => Object.keys(b.tiles).length - Object.keys(a.tiles).length)) {
    const file = `district-${g.id}.js`;
    writeFileSync(join(outDir, file), emitModule(g, structAssign.get(g.id)));
    const box = bbox(Object.keys(g.tiles));
    manifest.push(`| \`${g.id}\` | ${Object.keys(g.tiles).length} | ${box.xmin}..${box.xmax} | ${box.ymin}..${box.ymax} | ${g.name} |`);
    console.error(`[export] wrote ${file} (${Object.keys(g.tiles).length} tiles, ${(structAssign.get(g.id) || []).length} structures)`);
  }
  const man = [
    `# Whitemarch ward manifest (auto-generated)`, ``,
    `Regenerated from the live handcrafted_map row by`,
    `\`scripts/whitemarch-export-districts.mjs\`. Each row is one ward file.`,
    `Orientation: screen_x = x + y/2 (E = +), screen_y = y (S = +).`, ``,
    `| ward (DISTRICT_ID) | tiles | x range | y range | name |`,
    `|---|---|---|---|---|`,
    ...manifest, ``,
  ].join("\n");
  writeFileSync(join(outDir, "_MANIFEST.md"), man);
  console.error(`[export] wrote _MANIFEST.md`);
}

main().catch((e) => { console.error("ERROR:", e.message); process.exit(1); });
