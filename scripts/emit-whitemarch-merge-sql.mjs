#!/usr/bin/env node
// One-off helper for Wave 4 of the Whitemarch content expansion.
// Loads every src/data/whitemarch-districts/district-*.js and prints
// an SQL UPDATE that merges their TILES + STRUCTURES into the
// public.handcrafted_map id='whitemarch' row.
//
// The UPDATE uses jsonb concat (||):
//   - TILES: top-level keys in the new payload OVERWRITE existing keys
//     in the live tiles dict (jsonb || does this for objects), so a
//     rewritten tile lands cleanly. Untouched tiles stay as they are.
//   - STRUCTURES: the new array is APPENDED to the existing one
//     (jsonb || on arrays concatenates).
//
// Usage:
//   node scripts/emit-whitemarch-merge-sql.mjs           # prints SQL to stdout
//   node scripts/emit-whitemarch-merge-sql.mjs > out.sql # capture for review

import { readdirSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import { dirname, join } from "node:path";

const __filename = fileURLToPath(import.meta.url);
const __dirname  = dirname(__filename);
const DISTRICTS_DIR = join(__dirname, "..", "src", "data", "whitemarch-districts");

const files = readdirSync(DISTRICTS_DIR)
  .filter((f) => /^district-.+\.js$/.test(f))
  .sort();

const mergedTiles = {};
const newStructures = [];
let totalDistricts = 0;

for (const f of files) {
  const url = pathToFileURL(join(DISTRICTS_DIR, f)).href;
  const mod = await import(url);
  totalDistricts++;
  for (const [k, v] of Object.entries(mod.TILES || {})) {
    if (mergedTiles[k]) {
      console.error(`FATAL: coord ${k} declared by two modules`);
      process.exit(2);
    }
    mergedTiles[k] = v;
  }
  for (const s of (mod.STRUCTURES || [])) newStructures.push(s);
}

// Per-district output: emit ONE UPDATE per loaded module so each SQL
// payload fits comfortably into the size limits of a single
// mcp__supabase__execute_sql call. The order doesn't matter because jsonb
// concat is order-independent for non-overlapping keys, and we already
// proved zero collisions in the seed script's dry-run.

console.error(`[emit-sql] loaded ${totalDistricts} districts`);
console.error(`[emit-sql] merged tile keys: ${Object.keys(mergedTiles).length}`);
console.error(`[emit-sql] new structures: ${newStructures.length}`);

console.log(`-- Whitemarch content-expansion merge — Wave 4`);
console.log(`-- ${totalDistricts} districts, ${Object.keys(mergedTiles).length} tile rewrites/adds, ${newStructures.length} new structure(s)`);
console.log(`-- Generated by scripts/emit-whitemarch-merge-sql.mjs (one UPDATE per district)`);
console.log(``);

const PG_TAG = "$wmsat$"; // dollar-quote delimiter; unlikely to appear in any tile body

// Re-load each district one at a time so we can emit per-module UPDATEs.
for (const f of files) {
  const url = pathToFileURL(join(DISTRICTS_DIR, f)).href;
  const mod = await import(url);
  const tilesJson = JSON.stringify(mod.TILES || {});
  const structuresJson = JSON.stringify(mod.STRUCTURES || []);
  const tileCount = Object.keys(mod.TILES || {}).length;
  const structCount = (mod.STRUCTURES || []).length;
  console.error(`[emit-sql]   ${mod.DISTRICT_ID || f}: ${tileCount} tiles + ${structCount} structures (tiles payload: ${tilesJson.length} bytes)`);

  console.log(`-- ${mod.DISTRICT_ID || f} — ${tileCount} tile(s), ${structCount} structure(s)`);
  console.log(`update public.handcrafted_map`);
  console.log(`set tiles = tiles || ${PG_TAG}${tilesJson}${PG_TAG}::jsonb,`);
  console.log(`    sealed_structures = coalesce(sealed_structures, '[]'::jsonb) || ${PG_TAG}${structuresJson}${PG_TAG}::jsonb`);
  console.log(`where id = 'whitemarch';`);
  console.log(``);
}
