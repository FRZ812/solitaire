export function portraitTemplateId(record = {}) {
  const key = record.portraitKey || record.templateId;
  return typeof key === "string" ? key.replace(/^(?:template|archetype):/, "") : null;
}

export function portraitIdentityKey(record = {}) {
  const rawPortraitKey = typeof record.portraitKey === "string" ? record.portraitKey : null;
  if (rawPortraitKey && COMBAT_PORTRAIT_ALIASES[rawPortraitKey]) return COMBAT_PORTRAIT_ALIASES[rawPortraitKey];

  const canonicalKey = characterPortraitIdentityKey(record);
  if (canonicalKey) return canonicalKey;

  const templateId = typeof record.templateId === "string"
    ? record.templateId.replace(/^template:/, "")
    : null;
  if (templateId && LEGACY_VARIANTS[templateId]) return `template:${templateId}`;
  return null;
}

export function portraitVariantsFor(record = {}) {
  return CHARACTER_PORTRAIT_VARIANTS[portraitIdentityKey(record)] || EMPTY_VARIANTS;
}

export function parsePortraitVariantToken(value) {
  if (typeof value !== "string") return null;
  const match = value.match(BUILTIN_TOKEN_PATTERN);
  if (!match) return null;
  return { identityKey: match[1], variantNumber: Number(match[2]) };
}

export function isPortraitVariantToken(value) {
  return Boolean(parsePortraitVariantToken(value));
}

export function createPortraitVariantToken(recordOrIdentityKey, variantNumber) {
  const identityKey = typeof recordOrIdentityKey === "string"
    ? recordOrIdentityKey
    : portraitIdentityKey(recordOrIdentityKey);
  const variants = CHARACTER_PORTRAIT_VARIANTS[identityKey];
  const number = Number(variantNumber);
  if (!variants || !Number.isInteger(number) || number < 1 || number > variants.length) return null;
  return `builtin:${identityKey}:v${number}`;
}

function defaultPortraitVariantNumber(record) {
  const identityKey = portraitIdentityKey(record);
  const codexId = identityKey?.startsWith("codex:") ? identityKey.slice("codex:".length) : null;
  return codexId && Object.hasOwn(CODEX_ALTERNATIVES, codexId) ? 2 : 1;
}

export function selectedPortraitVariantNumber(record = {}, override = null) {
  const variants = portraitVariantsFor(record);
  if (!variants.length) return null;
  if (typeof override !== "string" || !override.trim()) return defaultPortraitVariantNumber(record);
  const parsed = parsePortraitVariantToken(override);
  if (!parsed) return null;
  return parsed.identityKey === portraitIdentityKey(record) && variants[parsed.variantNumber - 1]
    ? parsed.variantNumber
    : null;
}

function resolveBuiltInPortrait(record, value) {
  const parsed = parsePortraitVariantToken(value);
  if (!parsed || parsed.identityKey !== portraitIdentityKey(record)) return null;
  return CHARACTER_PORTRAIT_VARIANTS[parsed.identityKey]?.[parsed.variantNumber - 1] || null;
}

export function resolveCharacterPortrait(record = {}, fallback = null, override = null) {
  if (typeof override === "string" && override.trim()) {
    const builtIn = resolveBuiltInPortrait(record, override);
    if (builtIn) return builtIn;
    if (!isPortraitVariantToken(override)) return override;
  }
  if (typeof record.portrait === "string" && record.portrait.trim()) {
    const builtIn = resolveBuiltInPortrait(record, record.portrait);
    if (builtIn) return builtIn;
    if (!isPortraitVariantToken(record.portrait)) return record.portrait;
  }

  const variants = portraitVariantsFor(record);
  if (variants.length) return variants[defaultPortraitVariantNumber(record) - 1] || variants[0];

  const rawKey = record.portraitKey || record.templateId;
  const templateId = portraitTemplateId(record);
  const lookup = typeof rawKey === "string" && rawKey.startsWith("archetype:")
    ? `archetype:${templateId}`
    : templateId;
  return CHARACTER_PORTRAITS[lookup] || fallback;
}
